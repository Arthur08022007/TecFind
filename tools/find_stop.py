#!/usr/bin/env python3
"""Generate a local TEC timetable for the nearest stops within a radius."""
import argparse
import csv
from datetime import date
import io
import math
from pathlib import Path
import urllib.request
import zipfile

URL = "https://opendata-discovery-gtfs-static.api.production.belgianmobility.io/api/gtfs/feed/tec/static"
OUT = Path(__file__).resolve().parents[1] / "main/tec/tec_schedule_generated.h"


def read_rows(archive, name):
    with archive.open(name) as raw:
        text = io.TextIOWrapper(raw, encoding="utf-8-sig", newline="")
        yield from csv.DictReader(text)


def c_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("latitude", type=float, help="Latitude of the Indicator")
    parser.add_argument("longitude", type=float, help="Longitude of the Indicator")
    parser.add_argument("--radius-m", type=int, default=1000,
                        help="Maximum distance from the Indicator in metres (default: 1000)")
    parser.add_argument("--max-stops", type=int, default=12,
                        help="Maximum number of nearby stops compiled into the firmware (default: 12)")
    args = parser.parse_args()
    if args.radius_m <= 0 or args.max_stops <= 0:
        parser.error("--radius-m and --max-stops must be positive")

    print("Téléchargement des horaires GTFS TEC…")
    request = urllib.request.Request(URL, headers={"User-Agent": "TecFind/0.1"})
    with urllib.request.urlopen(request, timeout=90) as response:
        archive = zipfile.ZipFile(io.BytesIO(response.read()))

    stops = [row for row in read_rows(archive, "stops.txt") if row.get("location_type", "0") in ("", "0")]
    def meters(stop):
        lat, lon = math.radians(float(stop["stop_lat"])), math.radians(float(stop["stop_lon"]))
        p1 = math.radians(args.latitude)
        dp, dl = lat - p1, lon - math.radians(args.longitude)
        a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(lat) * math.sin(dl / 2) ** 2
        return 12_742_000 * math.asin(math.sqrt(a))

    nearby = sorted(((meters(stop), stop) for stop in stops), key=lambda item: item[0])
    nearby = [(distance, stop) for distance, stop in nearby if distance <= args.radius_m]
    if not nearby:
        raise SystemExit(f"Aucun arrêt TEC dans un rayon de {args.radius_m} m.")
    if len(nearby) > args.max_stops:
        print(f"{len(nearby)} arrêts trouvés; seuls les {args.max_stops} plus proches seront proposés sur l’écran.")
        nearby = nearby[:args.max_stops]
    stop_indexes = {stop["stop_id"]: index for index, (_, stop) in enumerate(nearby)}
    print(f"Arrêts proposés ({len(nearby)}) dans un rayon de {args.radius_m} m :")
    for index, (distance, stop) in enumerate(nearby):
        print(f"  {index + 1}. {stop['stop_name']} — {distance:.0f} m")

    stop_ids = set(stop_indexes)
    stop_times = [row for row in read_rows(archive, "stop_times.txt") if row["stop_id"] in stop_ids]
    trip_ids = {row["trip_id"] for row in stop_times}
    trips = {row["trip_id"]: row for row in read_rows(archive, "trips.txt") if row["trip_id"] in trip_ids}
    route_ids = {trip["route_id"] for trip in trips.values()}
    routes = {row["route_id"]: row for row in read_rows(archive, "routes.txt") if row["route_id"] in route_ids}
    service_ids = {trip["service_id"] for trip in trips.values()}
    calendars = {}
    if "calendar.txt" in archive.namelist():
        calendars = {row["service_id"]: row for row in read_rows(archive, "calendar.txt") if row["service_id"] in service_ids}
    exceptions = [row for row in read_rows(archive, "calendar_dates.txt") if row["service_id"] in service_ids] if "calendar_dates.txt" in archive.namelist() else []

    entries = []
    for row in stop_times:
        trip = trips.get(row["trip_id"])
        if not trip:
            continue
        route = routes.get(trip["route_id"], {})
        seconds = sum(int(part) * factor for part, factor in zip((row.get("departure_time") or row["arrival_time"]).split(":"), (3600, 60, 1)))
        entries.append((stop_indexes[row["stop_id"]], trip, route, seconds))

    weekdays = ("monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday")
    lines = [
        "/* Generated by tools/find_stop.py. Do not edit. */",
        "#pragma once",
        "typedef struct { const char *stop_id; const char *name; unsigned int distance_m; } tec_stop_t;",
        "typedef struct { unsigned short stop_index; const char *trip_id; const char *service_id; const char *line; const char *destination; int departure_seconds; } tec_static_departure_t;",
        "typedef struct { const char *service_id; const char *start_date; const char *end_date; unsigned char weekdays; } tec_service_calendar_t;",
        "typedef struct { const char *service_id; const char *date; unsigned char added; } tec_service_exception_t;",
        "static const tec_stop_t TEC_STOPS[] = {",
    ]
    for distance, stop in nearby:
        lines.append("  {%s,%s,%d}," % (c_string(stop["stop_id"]), c_string(stop["stop_name"]), round(distance)))
    lines += [
        "};",
        "static const tec_static_departure_t TEC_STATIC_DEPARTURES[] = {",
    ]
    for stop_index, trip, route, seconds in sorted(entries, key=lambda entry: (entry[0], entry[3])):
        line = route.get("route_short_name") or route.get("route_long_name") or "TEC"
        lines.append("  {%d,%s,%s,%s,%s,%d}," % (
            stop_index, c_string(trip["trip_id"]), c_string(trip["service_id"]), c_string(line),
            c_string(trip.get("trip_headsign", "")), seconds))
    lines += ["};", "static const tec_service_calendar_t TEC_SERVICE_CALENDAR[] = {"]
    for service_id, row in calendars.items():
        mask = sum((1 << index) for index, day in enumerate(weekdays) if row.get(day) == "1")
        lines.append("  {%s,%s,%s,%d}," % (c_string(service_id), c_string(row["start_date"]), c_string(row["end_date"]), mask))
    lines += ["};", "static const tec_service_exception_t TEC_SERVICE_EXCEPTIONS[] = {"]
    for row in exceptions:
        lines.append("  {%s,%s,%d}," % (c_string(row["service_id"]), c_string(row["date"]), 1 if row["exception_type"] == "1" else 0))
    lines += ["};", f"#define TEC_STOP_COUNT {len(nearby)}",
              f"#define TEC_STATIC_DEPARTURE_COUNT {len(entries)}",
              f"#define TEC_SERVICE_CALENDAR_COUNT {len(calendars)}",
              f"#define TEC_SERVICE_EXCEPTION_COUNT {len(exceptions)}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Horaires locaux générés : {len(entries)} passages dans {OUT}")
    print("La clé API se configure séparément avec idf.py menuconfig → TecFind.")


if __name__ == "__main__":
    main()
