#!/usr/bin/env python3
"""Draw the TEC screen bus icon and emit it as an LVGL 9 ARGB8888 image."""
from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 64
SCALE = 8
OUT = Path(__file__).resolve().parents[1] / "main/assets/tec_img_bus.c"


def draw() -> Image.Image:
    s = SCALE
    img = Image.new("RGBA", (SIZE * s, SIZE * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def box(x0, y0, x1, y1, r, fill):
        d.rounded_rectangle((x0 * s, y0 * s, x1 * s, y1 * s), radius=r * s, fill=fill)

    box(3, 17, 9, 29, 2, (37, 99, 235, 255))       # left mirror
    box(55, 17, 61, 29, 2, (37, 99, 235, 255))     # right mirror
    box(5, 15, 10, 18, 1, (37, 99, 235, 255))
    box(54, 15, 59, 18, 1, (37, 99, 235, 255))
    box(13, 52, 22, 61, 2, (30, 41, 82, 255))      # wheels
    box(42, 52, 51, 61, 2, (30, 41, 82, 255))
    box(8, 3, 56, 56, 10, (241, 245, 249, 255))    # body
    box(8, 40, 56, 56, 8, (219, 228, 240, 255))    # lower body
    box(8, 40, 56, 46, 0, (219, 228, 240, 255))
    box(22, 6, 42, 9, 1.5, (239, 68, 68, 255))     # roof light
    box(12, 12, 52, 38, 5, (59, 130, 246, 255))    # windshield
    d.polygon([(32 * s, 12 * s), (47 * s, 12 * s), (52 * s, 17 * s), (52 * s, 33 * s),
               (47 * s, 38 * s), (32 * s, 38 * s)], fill=(37, 99, 235, 255))
    d.ellipse((13 * s, 43 * s, 20 * s, 50 * s), fill=(251, 191, 36, 255))   # headlights
    d.ellipse((44 * s, 43 * s, 51 * s, 50 * s), fill=(251, 191, 36, 255))
    box(25, 45, 39, 48, 1.5, (148, 163, 184, 255))  # grille
    return img.resize((SIZE, SIZE), Image.LANCZOS)


def main() -> None:
    img = draw()
    rgba = img.tobytes()
    data = bytearray(len(rgba))
    data[0::4], data[1::4], data[2::4], data[3::4] = rgba[2::4], rgba[1::4], rgba[0::4], rgba[3::4]
    rows = [", ".join(f"0x{v:02X}" for v in data[i:i + 16]) for i in range(0, len(data), 16)]
    OUT.write_text(
        "/* Generated by tools/gen_bus_icon.py. Do not edit. */\n"
        "#include \"lvgl.h\"\n\n"
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN\n#define LV_ATTRIBUTE_MEM_ALIGN\n#endif\n\n"
        "static const LV_ATTRIBUTE_MEM_ALIGN uint8_t tec_img_bus_data[] = {\n    "
        + ",\n    ".join(rows) + ",\n};\n\n"
        "const lv_image_dsc_t tec_img_bus = {\n"
        "    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
        "    .header.cf = LV_COLOR_FORMAT_ARGB8888,\n"
        f"    .header.w = {SIZE},\n    .header.h = {SIZE},\n    .header.stride = {SIZE * 4},\n"
        "    .data_size = sizeof(tec_img_bus_data),\n"
        "    .data = tec_img_bus_data,\n};\n")
    img.resize((SIZE * 4, SIZE * 4), Image.NEAREST).save("/tmp/tec_bus_preview.png")


if __name__ == "__main__":
    main()
